def _engine_signals(cfg, spec, seed, bars):
    """Every candidate SignalEngine.evaluate produces on deterministic synthetic M5 data (all bars evaluated)."""
    cfg.analysis.gold_allowed_sessions = []
    cfg.analysis.allowed_sessions = []
    cfg.scoring.min_score = 55
    base = synthetic_ohlc(n=16000, tf=Timeframe.M5, seed=seed, start_price=2000.0 if spec.is_gold else 1.1,
                          vol=0.0006 if spec.is_gold else 0.0004)
    bt = Backtester(cfg)
    data = bt.prepare(spec.symbol, base, spec)
    engine = SignalEngine(cfg, None)
    m5 = data.frames[Timeframe.M5]
    close_ns = data.close_ns[Timeframe.M5]
    lo = int(m5.index.searchsorted(m5.index[0] + pd.Timedelta(days=50)))     # enough H4 history from here on
    hi = min(len(m5), lo + bars)
    out = []
    for i in range(lo, hi):
        now_ns = int(close_ns[i])
        now = pd.Timestamp(now_ns, unit="ns", tz="UTC").to_pydatetime()
        bid = float(m5["close"].iloc[i])
        res = engine.evaluate(MarketContext(spec.symbol, spec, now, bt._frames_at(data, now_ns), bid, bid + (0.25 if spec.is_gold else 0.00010)))
        if res.candidate is not None:
            out.append(res.candidate)
    return out


def _summary(cands, spec):
    from integrations import telegram_messages as tm
    rows, texts = [], []
    for n, c in enumerate(cands, 1):
        p = c.plan
        rows.append([c.created_at.isoformat(), c.direction.value, c.setup_type, round(c.score, 6),
                     round(p.entry, 6), round(p.stop_loss, 6), [round(x, 6) for x in p.take_profits], round(p.risk, 6)])
        texts.append(tm.signal_message(c, spec, n))
    return rows, hashlib.sha256("\n\x00".join(texts).encode("utf-8")).hexdigest()


def _event_texts():
    from integrations import telegram_messages as tm
